import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const publicDir = path.join(rootDir, "public");
const fontsDir = path.join(publicDir, "fonts");
const cssPath = path.join(fontsDir, "font-faces.css");
const manifestPath = path.join(fontsDir, "manifest.json");

/**
 * Google Fonts only serves the split WOFF2 + unicode-range format to modern
 * browser user agents; the default curl/Node UA would receive legacy formats.
 */
const USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

/**
 * The four families used by the design. Each request returns the same
 * unicode-range-split faces that `next/font` used to download: Latin/Greek/
 * Cyrillic slices for the Latin families and ~100 CJK slices for Noto Sans SC.
 */
const REQUESTS = [
  {
    family: "Inter",
    url: "https://fonts.googleapis.com/css2?family=Inter:wght@100..900&display=swap",
  },
  {
    family: "Noto Sans SC",
    url: "https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@100..900&display=swap",
  },
  {
    family: "JetBrains Mono",
    url: "https://fonts.googleapis.com/css2?family=JetBrains+Mono:ital,wght@0,100..800;1,100..800&display=swap",
  },
  {
    family: "Instrument Serif",
    url: "https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&display=swap",
  },
] as const;

interface ParsedFace {
  family: string;
  style: string;
  weight: string;
  url: string;
  subset?: string;
  unicodeRange?: string;
  /** Position in the upstream stylesheet, used to label unnamed CJK slices. */
  sliceIndex: number;
}

interface DownloadedFace extends ParsedFace {
  name: string;
  bytes: number;
}

function slug(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function parseFaces(css: string, source: string): ParsedFace[] {
  const faces: ParsedFace[] = [];
  const facePattern = /@font-face\s*\{([^}]*)\}/g;
  let previousEnd = 0;

  for (const match of css.matchAll(facePattern)) {
    const prefix = css.slice(previousEnd, match.index);
    const subset = prefix.match(/\/\*\s*([^*]+?)\s*\*\//)?.[1]?.trim();
    previousEnd = (match.index ?? 0) + match[0].length;

    const body = match[1];
    const family = body.match(/font-family:\s*'([^']+)'/)?.[1];
    const style = body.match(/font-style:\s*([a-z-]+)/)?.[1];
    const weight = body.match(/font-weight:\s*([\d ]+)/)?.[1];
    const url = body.match(/url\((https:\/\/[^)]+)\)/)?.[1];
    const unicodeRange = body.match(/unicode-range:\s*([^;]+);/)?.[1]?.trim();

    if (!family || !style || !weight || !url) {
      throw new Error(`[fonts] Could not parse an @font-face block from ${source}`);
    }

    faces.push({ family, style, weight, url, subset, unicodeRange, sliceIndex: faces.length });
  }

  if (faces.length === 0) {
    throw new Error(`[fonts] ${source} returned no @font-face blocks`);
  }
  return faces;
}

async function downloadFace(face: ParsedFace, directory: string): Promise<DownloadedFace> {
  const response = await fetch(face.url, { headers: { "User-Agent": USER_AGENT } });
  if (!response.ok) {
    throw new Error(`[fonts] ${response.status} ${response.statusText} for ${face.url}`);
  }

  const buffer = Buffer.from(await response.arrayBuffer());
  if (buffer.length < 100) {
    throw new Error(`[fonts] Suspiciously small font response (${buffer.length} B) for ${face.url}`);
  }

  const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 8);
  const subset = slug(face.subset ?? `slice-${face.sliceIndex}`);
  const name = `${slug(face.family)}-${slug(face.style)}-${slug(face.weight)}-${subset}-${hash}.woff2`;
  fs.writeFileSync(path.join(directory, name), buffer);
  return { ...face, name, bytes: buffer.length };
}

async function mapLimit<T, R>(
  items: readonly T[],
  limit: number,
  task: (item: T) => Promise<R>
): Promise<R[]> {
  const results = new Array<R>(items.length);
  let cursor = 0;

  async function worker() {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      results[index] = await task(items[index]);
    }
  }

  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return results;
}

function buildCss(faces: DownloadedFace[]): string {
  const lines = [
    "/*",
    " * Self-hosted webfont faces generated by scripts/fetch-fonts.ts.",
    " * Do not edit by hand; run `pnpm fonts -- --force` to refresh.",
    " */",
    "",
  ];

  for (const face of faces) {
    lines.push(`/* ${face.subset ?? `unicode-range slice ${face.sliceIndex}`} */`);
    lines.push("@font-face {");
    lines.push(`  font-family: '${face.family}';`);
    lines.push(`  font-style: ${face.style};`);
    lines.push(`  font-weight: ${face.weight};`);
    lines.push("  font-display: swap;");
    lines.push(`  src: url("/fonts/${face.name}") format("woff2");`);
    if (face.unicodeRange) lines.push(`  unicode-range: ${face.unicodeRange};`);
    lines.push("}");
    lines.push("");
  }

  return lines.join("\n");
}

function manifestSources() {
  return REQUESTS.map(({ family, url }) => ({ family, url }));
}

/**
 * A previous successful run leaves both the stylesheet and every referenced
 * WOFF2 in public/fonts/. Reuse it instead of hitting Google on every build.
 */
function cachedFontSummary(): { files: number; bytes: number } | null {
  if (!fs.existsSync(cssPath) || !fs.existsSync(manifestPath)) return null;

  let manifest: { sources?: unknown; files?: unknown; bytes?: unknown };
  try {
    manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  } catch (error) {
    if (error instanceof SyntaxError) return null;
    throw error;
  }

  if (JSON.stringify(manifest.sources) !== JSON.stringify(manifestSources())) return null;
  if (typeof manifest.files !== "number" || typeof manifest.bytes !== "number") return null;

  const css = fs.readFileSync(cssPath, "utf8");
  const urls = [...css.matchAll(/url\("(\/fonts\/[^"]+)"\)/g)].map((match) => match[1]);
  if (urls.length === 0) return null;

  const complete = urls.every((url) => {
    const file = path.join(publicDir, url.replace(/^\//, ""));
    return fs.existsSync(file) && fs.statSync(file).size > 0;
  });
  return complete ? { files: manifest.files, bytes: manifest.bytes } : null;
}

async function main() {
  const force = process.argv.includes("--force");
  if (!force) {
    const cached = cachedFontSummary();
    if (cached) {
      console.log(
        `[fonts] Reusing ${cached.files} self-hosted font files in public/fonts/ (${(cached.bytes / 1024 / 1024).toFixed(1)} MiB).`
      );
      return;
    }
  }

  console.log("[fonts] Downloading self-hosted font families from Google Fonts...");
  const parsed: ParsedFace[] = [];
  for (const { family, url } of REQUESTS) {
    const response = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
    if (!response.ok) {
      throw new Error(`[fonts] ${response.status} ${response.statusText} for ${url}`);
    }
    const faces = parseFaces(await response.text(), family);
    console.log(`[fonts] ${family}: ${faces.length} faces`);
    parsed.push(...faces);
  }

  // The CSS can reference the same URL more than once; download each once.
  const uniqueFaces = [...new Map(parsed.map((face) => [face.url, face])).values()];
  const tempDir = path.join(publicDir, `fonts.tmp-${process.pid}`);
  fs.rmSync(tempDir, { recursive: true, force: true });
  fs.mkdirSync(tempDir, { recursive: true });

  try {
    const downloaded = await mapLimit(uniqueFaces, 8, (face) => downloadFace(face, tempDir));
    const bytes = downloaded.reduce((sum, face) => sum + face.bytes, 0);

    fs.writeFileSync(path.join(tempDir, "font-faces.css"), buildCss(downloaded));
    fs.writeFileSync(
      path.join(tempDir, "manifest.json"),
      `${JSON.stringify({ sources: manifestSources(), files: downloaded.length, bytes }, null, 2)}\n`
    );

    fs.rmSync(fontsDir, { recursive: true, force: true });
    fs.renameSync(tempDir, fontsDir);
    console.log(
      `[fonts] Wrote ${downloaded.length} WOFF2 files (${(bytes / 1024 / 1024).toFixed(1)} MiB) to public/fonts/.`
    );
  } catch (error) {
    fs.rmSync(tempDir, { recursive: true, force: true });
    throw error;
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
